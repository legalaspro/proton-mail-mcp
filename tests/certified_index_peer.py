"""CONDSTORE peer extension over the existing AF_UNIX protocol fixtures.

Each mailbox has its own monotonic modification sequence. New UIDs, removals,
flag changes, and synthetic header faults advance that sequence. FETCH replies
are generated by the original peer after CHANGEDSINCE filters the UID set, so
all existing row/cost counters still count actual returned work.
"""

import re

from bridge_sim import BridgeSim


class CondstoreMixin:
    def __init__(self, *args, **kwargs):
        self.highest_modseq = {}
        self.message_modseq = {}
        self._observed_rows = {}
        super().__init__(*args, **kwargs)
        if "CONDSTORE" not in self.capabilities:
            self.capabilities.append("CONDSTORE")

    def sync(self):
        super().sync()
        for folder, mapping in self.uidmap.items():
            previous = self._observed_rows.setdefault(folder, {})
            sequences = self.message_modseq.setdefault(folder, {})
            self.highest_modseq.setdefault(folder, 1)
            current = {}
            for uid, pid in mapping.items():
                message = self.messages[pid]
                signature = (pid, message.headers, tuple(sorted(message.flags)))
                current[uid] = signature
                if previous.get(uid) != signature:
                    self.highest_modseq[folder] += 1
                    sequences[uid] = self.highest_modseq[folder]
            if set(previous) - set(current):
                self.highest_modseq[folder] += 1
            self._observed_rows[folder] = current
            for uid in set(sequences) - set(current):
                del sequences[uid]

    def handle(self, tag, op, uid_op, words, session, command):
        with self.lock:
            self.sync()
            if op == "STATUS":
                folder = words[1]
                values = (
                    f"MESSAGES {len(self.uidmap[folder])} "
                    f"UIDVALIDITY {self.uidvalidity[folder]} "
                    f"UIDNEXT {self.next_uid[folder]} "
                    f"HIGHESTMODSEQ {self.highest_modseq[folder]}"
                )
                return f'* STATUS "{folder}" ({values})\r\n'.encode() + tag + b" OK done\r\n"
            original = command
            if op == "FETCH":
                changed = re.fullmatch(
                    rb"(UID FETCH) (\S+) (\(.*\)) \(CHANGEDSINCE ([0-9]+)\)",
                    command,
                    re.IGNORECASE,
                )
                if changed:
                    folder = session.selected
                    uids = self._uids(changed.group(2).decode(), self.uidmap[folder])
                    threshold = int(changed.group(4))
                    uids = [uid for uid in uids if self.message_modseq[folder][uid] > threshold]
                    if not uids:
                        return tag + b" OK no changes\r\n"
                    spec = ",".join(map(str, uids)).encode()
                    command = b"UID FETCH " + spec + b" " + changed.group(3)
                    words = self._tokens(command)
            response = super().handle(tag, op, uid_op, words, session, command)
            if op in ("SELECT", "EXAMINE") and session.selected is not None:
                marker = tag + b" OK "
                sequence = self.highest_modseq[session.selected]
                response = response.replace(
                    marker, f"* OK [HIGHESTMODSEQ {sequence}] persistent\r\n".encode() + marker
                )
            elif op == "FETCH" and b"MODSEQ" in original.upper():
                folder = session.selected

                def modseq(match):
                    uid = int(match.group(2))
                    sequence = self.message_modseq[folder][uid]
                    return match.group(1) + f" MODSEQ ({sequence})".encode()

                response = re.sub(rb"(?m)^(\* [0-9]+ FETCH \(UID ([0-9]+))", modseq, response)
            return response


class CertifiedIndexPeer(CondstoreMixin, BridgeSim):
    """Protocol-compatible CONDSTORE variant; default fixtures stay unchanged."""
